CREATE DATABASE IF NOT EXISTS ujian_lan CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ujian_lan;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  nama VARCHAR(100) NOT NULL,
  kelas VARCHAR(30) DEFAULT NULL,
  role ENUM('admin','siswa') NOT NULL DEFAULT 'siswa'
);

CREATE TABLE IF NOT EXISTS exams (
  id INT AUTO_INCREMENT PRIMARY KEY,
  judul VARCHAR(150) NOT NULL,
  durasi_menit INT NOT NULL DEFAULT 60,
  aktif TINYINT(1) NOT NULL DEFAULT 0,
  acak_soal TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS questions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  exam_id INT NOT NULL,
  pertanyaan TEXT NOT NULL,
  a VARCHAR(500) NOT NULL,
  b VARCHAR(500) NOT NULL,
  c VARCHAR(500) NOT NULL,
  d VARCHAR(500) NOT NULL,
  e VARCHAR(500) NOT NULL DEFAULT '',
  kunci CHAR(1) NOT NULL,
  FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS attempts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  exam_id INT NOT NULL,
  user_id INT NOT NULL,
  mulai DATETIME NOT NULL,
  selesai DATETIME DEFAULT NULL,
  benar INT DEFAULT NULL,
  skor DECIMAL(5,2) DEFAULT NULL,
  UNIQUE KEY uq_attempt (exam_id, user_id),
  FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS answers (
  attempt_id INT NOT NULL,
  question_id INT NOT NULL,
  jawaban CHAR(1) NOT NULL,
  PRIMARY KEY (attempt_id, question_id),
  FOREIGN KEY (attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
  FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE
);
